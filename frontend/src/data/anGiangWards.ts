/**
 * Default initial ward: Phường Mỹ Bình, TP. Long Xuyên, Tỉnh An Giang
 * (Administrative center of An Giang Province)
 */
export const DEFAULT_WARD: WardItem = AN_GIANG_WARDS[0];

/**
 * Fast search & filter function for all wards/communes across An Giang
 */
export function searchAnGiangWards(
  keyword: string,
  filterType: 'ALL' | 'Phường' | 'Xã' | 'Thị trấn' = 'ALL'
): WardItem[] {
  const kw = keyword.toLowerCase().trim();

  return AN_GIANG_WARDS.filter((ward) => {
    // Type filter
    if (filterType !== 'ALL' && ward.type !== filterType) {
      return false;
    }

    if (!kw) return true;

    // Search by name, area, or code
    return (
      ward.name.toLowerCase().includes(kw) ||
      ward.area.toLowerCase().includes(kw) ||
      ward.officeAddress.toLowerCase().includes(kw) ||
      ward.code.toLowerCase().includes(kw)
    );
  });
}
